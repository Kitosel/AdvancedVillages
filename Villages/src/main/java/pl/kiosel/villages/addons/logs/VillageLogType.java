package pl.kiosel.villages.addons.logs;

import java.util.Locale;

public enum VillageLogType {

	VILLAGE_CREATED,
	VILLAGE_HEARTH_ADD,
	MEMBER_JOIN,
	MEMBER_LEAVE,
	MEMBER_KICK,
	MEMBER_PERMISSION,
	MEMBER_ROLE,
	BANK_DEPOSIT,
	BANK_WITHDRAW,
	QUEST_COMPLETED,
	SETTING_CHANGED,
	VILLAGE_UPGRADE,
	VILLAGE_ATTACK,
	ALLIANCE_CREATED,
	ALLIANCE_ENDED,
	WAR_DECLARED,
	WAR_STARTED,
	WAR_ENDED,
	DEVELOPMENT_UNLOCKED,
	UPKEEP_PAID,
	UPKEEP_MISSED,
	UPKEEP_PENALTY;

	public String getConfigKey() {
		return this.name().toLowerCase(Locale.ROOT).replace('_', '-');
	}
}
